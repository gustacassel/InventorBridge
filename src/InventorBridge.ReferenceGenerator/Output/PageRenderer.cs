using System.Text;
using InventorBridge.ReferenceGenerator.Model;

namespace InventorBridge.ReferenceGenerator.Output
{
    /// <summary>Builds the Markdown for the object pages, the enum pages and the index.</summary>
    public sealed class PageRenderer
    {
        private const int MaxReturnedByLinks = 40;
        private const int MaxUsedByLinks = 60;

        private static readonly string[] EntryPoints =
        [
            "Application", "Documents", "PartDocument", "AssemblyDocument", "DrawingDocument", "PresentationDocument",
            "PartComponentDefinition", "AssemblyComponentDefinition", "SheetMetalComponentDefinition", "TransientGeometry",
            "TransientObjects", "TransientBRep", "CommandManager", "UserInterfaceManager", "FileManager", "DesignProjectManager",
        ];

        private static readonly (ApiMemberKind Kind, string Title)[] MemberSections =
        [
            (ApiMemberKind.Property, "Properties"),
            (ApiMemberKind.Method, "Methods"),
            (ApiMemberKind.Event, "Events"),
        ];

        private readonly MergedApi api;
        private readonly VersionLabels versionLabels;

        public PageRenderer(MergedApi api, VersionLabels versionLabels)
        {
            this.api = api;
            this.versionLabels = versionLabels;
        }

        public string RenderObjectPage(MergedType type)
        {
            var page = new StringBuilder();
            page.AppendLine($"# {type.Name}").AppendLine();
            page.AppendLine($"Inventor API object · versions: {versionLabels.Range(type.Versions)} · [index](../index.md)").AppendLine();

            if (type.Ancestors.Count > 0)
            {
                var ancestors = string.Join(" → ", type.Ancestors.Select(LinkFromPage));
                page.AppendLine($"**Inherits from:** {ancestors}. The interop flattens COM inheritance: the members of these types are already listed here, and the object can be cast to them (and back, when its actual type is this one).").AppendLine();
            }

            if (type.AccessPath is not null && type.Name != "Application")
            {
                page.AppendLine($"**How to get it:** `{type.AccessPath}`").AppendLine();
            }

            AppendInterfaceBlock(page, type);

            var hiddenCount = type.Members.Values.Count(member => member.IsHidden);
            if (hiddenCount > 0)
            {
                page.AppendLine($"{hiddenCount} hidden member(s) omitted: they are obsolete or internal and should not be used.").AppendLine();
            }

            if (type.ReturnedBy.Count > 0)
            {
                page.AppendLine("**Returned by:** " + MemberLinks(type.ReturnedBy, MaxReturnedByLinks)).AppendLine();
            }

            var referencedTypes = GetReferencedTypes(type);
            if (referencedTypes.Count > 0)
            {
                page.AppendLine("**Referenced types:** " + string.Join(", ", referencedTypes.Select(LinkFromPage))).AppendLine();
            }

            return page.ToString();
        }

        public string RenderEnumPage(MergedType type)
        {
            var page = new StringBuilder();
            page.AppendLine($"# {type.Name}").AppendLine();
            page.AppendLine($"Inventor API enum · versions: {versionLabels.Range(type.Versions)} · [index](../index.md)").AppendLine();

            page.AppendLine("```csharp").AppendLine($"enum {type.Name}").AppendLine("{");
            foreach (var value in type.EnumValues.Values.OrderBy(value => value.Value))
            {
                page.AppendLine($"    {value.Name} = {value.Value},{versionLabels.Note(value.Versions)}");
            }
            page.AppendLine("}").AppendLine("```").AppendLine();

            if (type.UsedBy.Count > 0)
            {
                page.AppendLine("**Used by:** " + MemberLinks(type.UsedBy, MaxUsedByLinks)).AppendLine();
            }

            return page.ToString();
        }

        public string RenderIndexPage()
        {
            var page = new StringBuilder();
            page.AppendLine("# Inventor API reference").AppendLine();
            page.AppendLine("Generated by `InventorBridge.ReferenceGenerator` from `Autodesk.Inventor.Interop.dll`. Do not edit by hand: run the generator again.").AppendLine();

            page.AppendLine("| Version | Assembly |").AppendLine("|---|---|");
            foreach (var version in api.SourceVersions)
            {
                page.AppendLine($"| {version.Version} | {version.AssemblyVersion} |");
            }
            page.AppendLine();

            page.AppendLine("## How to use").AppendLine();
            page.AppendLine("- Look up a member: `grep` in `members.tsv` (columns: type, member, kind, signature, versions).");
            page.AppendLine("- Open `objects/<Name>.md` or `enums/<Name>.md`. Each object page has the interface in pseudo-C#, what returns it, the types it references and an example path from `Application` (one possible path, not the only one; `→ (Type)` is a cast).");
            page.AppendLine("- \"Inherits from\" lists the object's COM ancestors: the interop does not show inheritance, but `PartDocument` is also a `Document`, `ExtrudeFeature` is also a `PartFeature`, and so on.");
            page.AppendLine("- Signatures: `object` is a COM VARIANT; `= Missing` marks an optional parameter that can be omitted.");
            page.AppendLine("- `// since 20xx` marks members that do not exist in every version listed above.");
            page.AppendLine("- The API uses internal units: length in cm, angles in radians, regardless of the document units.");
            page.AppendLine();

            page.AppendLine("## Entry points").AppendLine();
            var entryPointLinks = EntryPoints.Where(api.Types.ContainsKey).Select(LinkFromIndex);
            page.AppendLine(string.Join(" · ", entryPointLinks)).AppendLine();

            var objects = api.SortedVisibleObjects.ToList();
            page.AppendLine($"## Objects ({objects.Count})").AppendLine();
            AppendAlphabeticalLinks(page, objects);

            var enums = api.SortedVisibleEnums.ToList();
            page.AppendLine($"## Enums ({enums.Count})").AppendLine();
            AppendAlphabeticalLinks(page, enums);

            return page.ToString();
        }

        /// <summary>The interface in pseudo-C#, with visible properties, methods and events in alphabetical order.</summary>
        private void AppendInterfaceBlock(StringBuilder page, MergedType type)
        {
            page.AppendLine("```csharp").AppendLine($"interface {type.Name}").AppendLine("{");

            foreach (var (kind, title) in MemberSections)
            {
                var members = type.VisibleMembers
                    .Where(member => member.Kind == kind)
                    .OrderBy(member => member.Name, StringComparer.Ordinal)
                    .ToList();

                if (members.Count == 0)
                {
                    continue;
                }

                page.AppendLine($"    // {title}");
                foreach (var member in members)
                {
                    page.AppendLine("    " + SignatureFormatter.Format(member.Latest) + versionLabels.MemberNote(member));
                }
            }

            page.AppendLine("}").AppendLine("```").AppendLine();
        }

        /// <summary>Types with a page that appear in the object's signatures (return types and parameters).</summary>
        private List<string> GetReferencedTypes(MergedType type)
        {
            return type.VisibleMembers
                .SelectMany(member => member.Latest.Parameters.Select(parameter => parameter.Type).Append(member.Latest.ReturnType))
                .Select(TypeNames.WithoutArray)
                .Distinct()
                .Where(typeName => typeName != type.Name && api.HasPage(typeName))
                .Order(StringComparer.Ordinal)
                .ToList();
        }

        private void AppendAlphabeticalLinks(StringBuilder page, List<MergedType> types)
        {
            foreach (var group in types.GroupBy(type => char.ToUpperInvariant(type.Name[0])))
            {
                var links = string.Join(" · ", group.Select(type => LinkFromIndex(type.Name)));
                page.AppendLine($"**{group.Key}** {links}  ").AppendLine();
            }
        }

        /// <summary>"Owner.Member" list with a link on the owner, limited to <paramref name="max"/> items.</summary>
        private string MemberLinks(List<string> references, int max)
        {
            var links = references
                .Order(StringComparer.Ordinal)
                .Take(max)
                .Select(reference =>
                {
                    var dot = reference.IndexOf('.');
                    return $"{LinkFromPage(reference[..dot])}.{reference[(dot + 1)..]}";
                });

            var remaining = references.Count > max ? $" and {references.Count - max} more (see `members.tsv`)" : "";
            return string.Join(", ", links) + remaining;
        }

        /// <summary>Link used inside objects/ and enums/.</summary>
        private string LinkFromPage(string typeName)
        {
            return Link(typeName, "../");
        }

        /// <summary>Link used in index.md, at the root of the reference.</summary>
        private string LinkFromIndex(string typeName)
        {
            return Link(typeName, "");
        }

        /// <summary>Link to the type's page, or just the name as code if the type has no page.</summary>
        private string Link(string typeName, string prefix)
        {
            if (!api.HasPage(typeName))
            {
                return $"`{typeName}`";
            }

            var folder = api.Types[typeName].Kind == ApiTypeKind.Enum ? "enums" : "objects";
            return $"[{typeName}]({prefix}{folder}/{typeName}.md)";
        }
    }
}
